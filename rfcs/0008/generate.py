# --- Settling an environment (section 7, steps 2, 5 and 6) -------------------------------------


def settle(contract, environment):
    """Records per kind, closed kinds, ignored facts and conflicts, as section 7 defines them."""
    kinds = contract["kinds"]
    sources = contract["evidence"]["sources"]
    accepted, ignored = [], []
    for fact in environment["facts"]:
        if fact["kind"] in kinds and fact["source"] in sources.get(fact["kind"], []):
            accepted.append(fact)
        else:
            ignored.append(fact["id"])
    groups = {}
    for fact in accepted:
        key = tuple(json.dumps(fact["fields"].get(name), sort_keys=True) for name in kinds[fact["kind"]]["key"])
        groups.setdefault((fact["kind"], key), []).append(fact)
    records = {kind: [] for kind in kinds}
    opened, conflicts = set(), []
    policy = contract["evidence"]["conflicts"]
    for (kind, _), facts in groups.items():
        if all(f["fields"] == facts[0]["fields"] for f in facts):
            records[kind].append((facts[0]["id"], facts[0]["fields"]))
            continue
        entry = {"facts": sorted(f["id"] for f in facts), "kind": kind}
        used = None
        if policy == "source-order":
            present = {f["source"] for f in facts}
            first = next(s for s in sources[kind] if s in present)
            preferred = [f for f in facts if f["source"] == first]
            if all(f["fields"] == preferred[0]["fields"] for f in preferred):
                used = preferred[0]
                entry["resolvedTo"] = used["id"]
        if used is None:
            opened.add(kind)
        else:
            records[kind].append((used["id"], used["fields"]))
        conflicts.append(entry)
    for kind in records:
        records[kind] = [fields for _, fields in sorted(records[kind])]
    cutoff_input = contract["evaluation"].get("cutoff")
    cutoff = int(environment["inputs"][cutoff_input]) if cutoff_input else None
    closed = {
        kind
        for kind in kinds
        if kind not in opened
        and any(
            c["kind"] == kind and c["source"] in sources.get(kind, []) and (cutoff is None or int(c["asOf"]) >= cutoff)
            for c in environment["complete"]
        )
    }
    conflicts.sort(key=lambda c: (c["kind"], c["facts"]))
    return records, closed, ignored, conflicts


# --- Translation into the Lean model -------------------------------------------------------------


def lean_string(text):
    return json.dumps(text, ensure_ascii=False)


def lean_ty(ty):
    t = ty["type"]
    if t == "decimal":
        return f"(.decimal {ty['scale']})"
    if t == "money":
        return f"(.money {lean_string(ty['currency'])} {ty['scale']})"
    return "." + t


def lean_value(ty, value):
    t = ty["type"]
    if t == "text":
        return f"(.text {lean_string(value)})"
    if t == "bool":
        return f"(.bool {'true' if value else 'false'})"
    return f"(.num ({int(value)}))"


def lean_term(term, contract, kinds_of):
    if "lit" in term:
        return f"(.lit {lean_ty(term['of'])} {lean_value(term['of'], term['lit'])})"
    if "input" in term:
        return f"(.input {lean_string(term['input'])})"
    if "param" in term:
        return f"(.param {lean_string(term['param'])})"
    if "var" in term:
        return f"(.field {lean_string(term['var'])} {lean_string(term['field'])})"
    if "add" in term or "sub" in term:
        op = "add" if "add" in term else "sub"
        left, right = (lean_term(t, contract, kinds_of) for t in term[op])
        return f"(.{op} {left} {right})"
    if "scale" in term:
        return f"(.scale ({int(term['scale'])}) {lean_term(term['of'], contract, kinds_of)})"
    if "abs" in term:
        return f"(.abs {lean_term(term['abs'], contract, kinds_of)})"
    raise ValueError(f"not a term: {term}")


def lean_pred(pred, contract, kinds_of):
    def sub(p):
        return lean_pred(p, contract, kinds_of)

    if "aggregate" in pred:
        fn = ".count" if pred["aggregate"] == "count" else f"(.sum {lean_string(pred['field'])})"
        body = sub(pred["where"])
        bound = lean_term(pred["than"], contract, kinds_of)
        return f"(.agg {fn} {lean_string(pred['of'])} {lean_string(pred['in'])} {body} .{pred['cmp']} {bound})"
    if "cmp" in pred:
        left, right = lean_term(pred["left"], contract, kinds_of), lean_term(pred["right"], contract, kinds_of)
        return f"(.cmp .{pred['cmp']} {left} {right})"
    for op in ("and", "or"):
        if op in pred:
            parts = [sub(p) for p in pred[op]]
            lowered = parts[-1]
            for part in reversed(parts[:-1]):
                lowered = f"(.{op} {part} {lowered})"
            return lowered
    if "not" in pred:
        return f"(.not {sub(pred['not'])})"
    if "exists" in pred:
        return f"(.ex {lean_string(pred['exists'])} {lean_string(pred['in'])} {sub(pred['where'])})"
    if "forall" in pred:
        return f"(.all {lean_string(pred['forall'])} {lean_string(pred['in'])} {sub(pred['holds'])})"
    raise ValueError(f"not a predicate: {pred}")


def lean_lookup(name, entries, default):
    """`fun name => if name = "a" then … else …`, over (name, Lean expression) pairs."""
    if not entries:
        return f"fun _ => {default}"
    body = default
    for key, value in reversed(entries):
        body = f"if {name} = {lean_string(key)} then {value} else {body}"
    return f"fun {name} => {body}"


def lean_case(name, contract, environment, expected):
    records, closed, _, _ = settle(contract, environment)
    kinds = contract["kinds"]
    inputs = [(k, f"some {lean_value(contract['inputs'][k], v)}") for k, v in sorted(environment["inputs"].items())]
    params = [(k, f"some {lean_value(p['type'], p['value'])}") for k, p in sorted(contract["policy"].items())]

    def record(kind, fields):
        pairs = ", ".join(
            f"({lean_string(f)}, {lean_value(kinds[kind]['fields'][f], v)})" for f, v in sorted(fields.items())
        )
        return f"⟨[{pairs}]⟩"

    record_lists = [(k, "[" + ", ".join(record(k, f) for f in rs) + "]") for k, rs in sorted(records.items()) if rs]
    closed_kinds = [(k, "true") for k in sorted(closed)]
    preds = [lean_pred(r["predicate"], contract, kinds) for r in contract["requires"]]
    values = ", ".join("." + r["value"].lower() for r in expected["requirements"])
    decision = "." + expected["decision"].lower()
    return "\n".join(
        [
            f"def {name}.env : Env where",
            f"  inputs := {lean_lookup('n', inputs, 'none')}",
            f"  params := {lean_lookup('n', params, 'none')}",
            f"  records := {lean_lookup('k', record_lists, '[]')}",
            f"  closed := {lean_lookup('k', closed_kinds, 'false')}",
            "",
            f"def {name}.requirements : List WCL2.Pred := [",
            ",\n".join("  " + p for p in preds),
            "]",
            "",
            f"theorem {name} :",
            f"    {name}.requirements.map (fun r => r.eval {name}.env []) = [{values}] ∧",
            f"      WCL2.evaluate {name}.env {name}.requirements = {decision} := by",
            "  decide",
        ]
    )


# --- Cases -----------------------------------------------------------------------------------------


def lean_name(label):
    return "v_" + re.sub(r"[^A-Za-z0-9]", "_", label)


def add_case(path, label, case, contract, description):
    """Record one case: a model check if it has a result, a note if it is a refusal."""
    expected = case["expected"]
    if "refused" in expected:
        NOT_CHECKED.append((label, expected["refused"], description))
        return
    records, closed, ignored, conflicts = settle(contract, case["environment"])
    if expected["ignored"] != ignored or expected["conflicts"] != conflicts:
        sys.exit(f"{label}: settling the environment does not reproduce the expected ignored and conflicts")
    if [r["id"] for r in expected["requirements"]] != [r["id"] for r in contract["requires"]]:
        sys.exit(f"{label}: the expected requirements are not the contract's, in order")
    CHECKED.append((lean_name(label), label, contract, case["environment"], expected))


def restate(contract):
    """A Language 1 contract in Language 2's form: the same contract, under the new identifier."""
    restated = json.loads(json.dumps(contract))
    restated["language"] = LANGUAGE
    return restated


def build_restated():
    for folder in ("cases", "differential"):
        for source in sorted((V1 / folder).glob("*.json")):
            value = json.loads(source.read_text(encoding="utf-8"))
            label = f"{folder}/{source.name}"
            if source.name == "27-contract-other-language.json":
                # Language 1's case for a language it does not define names work-contract-2, which is
                # this language. Restated, it names work-contract-1: versions are never interchanged.
                value["contract"]["language"] = "work-contract-1"
                value["description"] = "A language version this language does not define: Language 1."
                NOT_CHECKED.append((label, value["expected"]["refused"], value["description"]))
                FILES.append((label, value))
                continue
            value["contract"] = restate(value["contract"])
            if "cases" in value:
                for index, case in enumerate(value["cases"]):
                    add_case(label, f"{label}#{index}", case, value["contract"], "")
            else:
                add_case(label, label, value, value["contract"], value.get("description", ""))
            FILES.append((label, value))


def text():
    return {"type": "text"}


def eur():
    return {"currency": "EUR", "scale": 2, "type": "money"}


def time():
    return {"type": "time"}


def field(var, name):
    return {"field": name, "var": var}


def cmp(op, left, right):
    return {"cmp": op, "left": left, "right": right}


def lit_int(n):
    return {"lit": str(n), "of": {"type": "int"}}


def contract(identity, inputs, kinds, requires, cutoff=True, policy=None):
    value = {
        "evaluation": {"cutoff": "cutoff", "semantics": "kleene-1"} if cutoff else {"semantics": "kleene-1"},
        "evidence": {"conflicts": "unknown", "sources": {kind: ["erp"] for kind in kinds}},
        "identity": {"id": identity, "version": "1"},
        "inputs": dict(inputs, **({"cutoff": time()} if cutoff else {})),
        "kinds": kinds,
        "language": LANGUAGE,
        "policy": policy or {},
        "requires": sorted(requires, key=lambda r: r["id"]),
    }
    return value


def facts(*entries):
    """Facts in ascending order of identifier, all from the accepted source unless one says otherwise."""
    out = []
    for index, (kind, fields, *source) in enumerate(entries, start=1):
        out.append({"fields": fields, "id": f"f{index:02d}-{kind}", "kind": kind, "source": source[0] if source else "erp"})
    return out


CUTOFF = "1767225600"


def environment(inputs, fact_list, complete_kinds):
    return {
        "complete": [{"asOf": CUTOFF, "kind": k, "source": "erp"} for k in sorted(complete_kinds)],
        "facts": fact_list,
        "inputs": dict(inputs, cutoff=CUTOFF),
    }


def result(contract_value, env, values, decision, ignored=(), conflicts=()):
    ids = [r["id"] for r in contract_value["requires"]]
    return {
        "conflicts": list(conflicts),
        "decision": decision,
        "ignored": list(ignored),
        "requirements": [{"id": i, "value": v} for i, v in zip(ids, values)],
    }


def new_case(name, description, contract_value, env, expected):
    label = f"cases/{name}.json"
    value = {"contract": contract_value, "description": description, "environment": env, "expected": expected}
    add_case(label, label, value, contract_value, description)
    FILES.append((label, value))


