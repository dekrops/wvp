def audit_file(current):
    block = [AUDIT_BEGIN] + [f"#print axioms WCL2.Vectors.{name}" for name, *_ in CHECKED] + [AUDIT_END]
    if AUDIT_BEGIN in current:
        head = current[: current.index(AUDIT_BEGIN)]
        tail = current[current.index(AUDIT_END) + len(AUDIT_END) :]
        return head + "\n".join(block) + tail
    return current.rstrip("\n") + "\n\n" + "\n".join(block) + "\n"


