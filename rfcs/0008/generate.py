#!/usr/bin/env python3
"""Writes the vectors proposed by RFC 0008 for Work Contract Language 2, and their Lean checks.

    python3 rfcs/0008/generate.py [--check]

Two outputs, from one list of cases:

* `rfcs/0008/vectors/work-contract/v2/`: the cases, in the format of the published Language 1
  corpus (`test-vectors/work-contract/v1`). `cases/` and `differential/` restate every published
  Language 1 case in Language 2's form, with its Language 1 expectation. `cases/2*-` are new: the
  arithmetic, the aggregates, the worked examples and the refusals the RFC lists.
* `rfcs/0008/formal/WCL2/Vectors.lean`: for every case with a result, a theorem that the Lean model
  of RFC 0008 (`WCL2.Pred.eval`, `WCL2.evaluate`) gives exactly its expected requirement values and
  decision, proved by `decide`. `check.sh` builds and audits them, so every such expectation is a
  checked statement about the model, not this generator's opinion.

The model defines evaluation over a settled environment (section 7, steps 7 and 8). This generator
settles the environment from the case (steps 2, 5 and 6: acceptance, one record per key, closed
kinds) and translates the contract's predicates; that part is tested, not proved: it must reproduce
the `ignored` and `conflicts` of every published Language 1 case, and the model must then reproduce
every published requirement value. Refusals (static rules, conformance, the work bound, the range)
are not in the model; their expectations rest on the RFC's text, and `vectors/README.md` lists them.

Standard library only, deterministic; --check fails if any output differs from what would be written.
These are proposals. They are not part of the conformance corpus.
"""

