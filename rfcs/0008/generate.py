def build_refusals():
    base_env = environment({"invoice": "INV-1"}, facts(("invoice", {"amount": "10050", "id": "INV-1"})), {"invoice", "paymentMatch"})

    def with_requirement(pred, kinds=None):
        return contract("refusals", {"invoice": text()}, kinds or PAYMENT_KINDS, [{"id": "R", "predicate": pred}])

    usd = {"currency": "USD", "scale": 2, "type": "money"}
    eur3 = {"currency": "EUR", "scale": 3, "type": "money"}
    inv_amount = field("i", "amount")

    def about_invoice(body):
        return {"exists": "i", "in": "invoice", "where": body}

    refusal("260-add-two-currencies", "add of EUR and USD.", with_requirement(about_invoice(cmp("le", {"add": [inv_amount, {"lit": "1", "of": usd}]}, inv_amount))), base_env, "CONTRACT_ILL_FORMED")
    refusal("261-add-two-scales", "add of EUR at scale 2 and EUR at scale 3.", with_requirement(about_invoice(cmp("le", {"add": [inv_amount, {"lit": "1", "of": eur3}]}, inv_amount))), base_env, "CONTRACT_ILL_FORMED")
    refusal("262-time-plus-time", "time + time has no meaning; only time − time (an int) does.",
            with_requirement(cmp("le", {"add": [{"input": "cutoff"}, {"input": "cutoff"}]}, {"input": "cutoff"})), base_env, "CONTRACT_ILL_FORMED")
    agg = {"aggregate": "sum", "cmp": "le", "in": "paymentMatch", "of": "m", "than": {"lit": "0", "of": eur()}, "where": cmp("eq", field("m", "invoice"), {"input": "invoice"})}
    refusal("263-sum-of-text", "sum of a text field.", with_requirement(dict(agg, field="invoice")), base_env, "CONTRACT_ILL_FORMED")
    refusal("264-sum-of-optional", "sum of an optional field.",
            with_requirement(dict(agg, field="fee"), kinds=dict(PAYMENT_KINDS, paymentMatch={"fields": dict(PAYMENT_KINDS["paymentMatch"]["fields"], fee=dict(eur(), optional=True)), "key": ["id"]})),
            base_env, "CONTRACT_ILL_FORMED")
    refusal("265-aggregate-variable-outside", "The aggregate's variable is bound in its body only; its bound cannot read it.",
            with_requirement(dict(agg, field="amount", than=field("m", "amount"))), base_env, "CONTRACT_ILL_FORMED")
    deep = {"exists": "a", "in": "invoice", "where": {"exists": "b", "in": "invoice", "where": {"exists": "c", "in": "invoice", "where": dict(agg, field="amount")}}}
    refusal("266-aggregate-too-deep", "An aggregate under three quantifiers: its nesting counts toward the depth limit of 3.", with_requirement(deep), base_env, "CONTRACT_ILL_FORMED")
    big = "9000000000000000000"
    overflow_env = environment({"invoice": "INV-1"}, facts(("invoice", {"amount": "10050", "id": "INV-1"}), match("M-1", big), match("M-2", big)), {"invoice", "paymentMatch"})
    refusal("267-sum-out-of-range", "9e18 + 9e18 is not below 2^63: the evaluation refuses rather than wrap, saturate or call it UNKNOWN.",
            with_requirement(dict(agg, field="amount")), overflow_env, "ARITHMETIC_RANGE")


