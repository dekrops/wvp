#!/usr/bin/env python3
"""Writes the vectors proposed by RFC 0012 (when a requirement applies), and their Lean checks.

    python3 rfcs/0012/generate.py [--check]

Built on RFC 0008's generator (`rfcs/0008/generate.py`), which it imports for settling an
environment, translating predicates and the shape of a case. Two outputs:

* `rfcs/0012/vectors/work-contract/v2/cases/4*`: the cases RFC 0012's Vectors section lists.
* `rfcs/0012/formal/Applies/Vectors.lean`: for every case with a result, a theorem that the Lean
  model of RFC 0012 (`Applies.result`, `Applies.evaluate`, over Language 2's `WCL2.Pred.eval`) gives
  exactly its expected requirement values and decision, proved by `decide`. `check.sh` builds and
  audits them.

Refusals (static rules, the arithmetic range) are not in the model; they rest on the RFC's text, and
`vectors/README.md` lists them. Standard library only, deterministic; --check fails if any output
differs from what would be written. These are proposals, not part of the conformance corpus.
"""

import importlib.util
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
_spec = importlib.util.spec_from_file_location("rfc0008_generate", HERE.parent / "0008" / "generate.py")
g = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(g)

OUT = HERE / "vectors" / "work-contract" / "v2"
LEAN = HERE / "formal" / "Applies" / "Vectors.lean"
AUDIT = HERE / "formal" / "Audit.lean"
AUDIT_BEGIN = "-- Generated by rfcs/0012/generate.py: one theorem per proposed vector with a result."
AUDIT_END = "-- End of generated vector theorems."

FILES = []  # (path relative to OUT, value)
CHECKED = []  # (theorem name, file label, contract, environment, expected)
NOT_CHECKED = []  # (file label, refusal code, description)

RESULTS = {"TRUE": ".true", "FALSE": ".false", "UNKNOWN": ".unknown", "NOT_APPLICABLE": ".notApplicable"}
OUTCOMES = {"SUPPORTED": ".supported", "CONTRADICTED": ".contradicted", "UNDETERMINED": ".undetermined",
            "NOT_APPLICABLE": ".notApplicable"}


# --- Translation into the Lean model of RFC 0012 ---------------------------------------------------


def lean_requirement(requirement, contract):
    holds = g.lean_pred(requirement["predicate"], contract, contract["kinds"])
    if "appliesWhen" in requirement:
        return f"⟨some {g.lean_pred(requirement['appliesWhen'], contract, contract['kinds'])}, {holds}⟩"
    return f"⟨none, {holds}⟩"


def lean_case(name, contract, environment, expected):
    records, closed, _, _ = g.settle(contract, environment)
    kinds = contract["kinds"]
    inputs = [(k, f"some {g.lean_value(contract['inputs'][k], v)}") for k, v in sorted(environment["inputs"].items())]
    params = [(k, f"some {g.lean_value(p['type'], p['value'])}") for k, p in sorted(contract["policy"].items())]

    def record(kind, fields):
        pairs = ", ".join(
            f"({g.lean_string(f)}, {g.lean_value(kinds[kind]['fields'][f], v)})" for f, v in sorted(fields.items())
        )
        return f"⟨[{pairs}]⟩"

    record_lists = [(k, "[" + ", ".join(record(k, f) for f in rs) + "]") for k, rs in sorted(records.items()) if rs]
    closed_kinds = [(k, "true") for k in sorted(closed)]
    requirements = [lean_requirement(r, contract) for r in contract["requires"]]
    values = ", ".join(RESULTS[r["value"]] for r in expected["requirements"])
    decision = OUTCOMES[expected["decision"]]
    evaluation = f"(fun p => WCL2.Pred.eval {name}.env p [])"
    return "\n".join(
        [
            f"def {name}.env : Env where",
            f"  inputs := {g.lean_lookup('n', inputs, 'none')}",
            f"  params := {g.lean_lookup('n', params, 'none')}",
            f"  records := {g.lean_lookup('k', record_lists, '[]')}",
            f"  closed := {g.lean_lookup('k', closed_kinds, 'false')}",
            "",
            f"def {name}.requirements : List (Requirement WCL2.Pred) := [",
            ",\n".join("  " + r for r in requirements),
            "]",
            "",
            f"theorem {name} :",
            f"    {name}.requirements.map (result {evaluation}) = [{values}] ∧",
            f"      evaluate {evaluation} {name}.requirements = {decision} := by",
            "  decide",
        ]
    )


# --- Cases -----------------------------------------------------------------------------------------


def add_case(label, case, contract, description):
    expected = case["expected"]
    if "refused" in expected:
        NOT_CHECKED.append((label, expected["refused"], description))
        return
    _, _, ignored, conflicts = g.settle(contract, case["environment"])
    if expected["ignored"] != ignored or expected["conflicts"] != conflicts:
        sys.exit(f"{label}: settling the environment does not reproduce the expected ignored and conflicts")
    if [r["id"] for r in expected["requirements"]] != [r["id"] for r in contract["requires"]]:
        sys.exit(f"{label}: the expected requirements are not the contract's, in order")
    CHECKED.append((g.lean_name(label), label, contract, case["environment"], expected))


def new_case(name, description, contract_value, env, expected):
    label = f"cases/{name}.json"
    value = {"contract": contract_value, "description": description, "environment": env, "expected": expected}
    add_case(label, value, contract_value, description)
    FILES.append((label, value))


def refusal(name, description, contract_value, env, code):
    new_case(name, description, contract_value, env, {"refused": code})


INVOICE_KINDS = {
    "invoice": {
        "fields": {
            "gross": g.eur(),
            "id": g.text(),
            "net": g.eur(),
            "reverseCharge": {"optional": True, "type": "bool"},
            "tax": g.eur(),
        },
        "key": ["id"],
    }
}


def the_invoice(body):
    return {"exists": "i", "in": "invoice", "where": {"and": [g.cmp("eq", g.field("i", "id"), {"input": "invoice"}), body]}}


NOT_REVERSE_CHARGE = the_invoice(g.cmp("eq", g.field("i", "reverseCharge"), {"lit": False, "of": {"type": "bool"}}))
TAX_AT_19 = the_invoice(g.cmp("eq", {"scale": "100", "of": g.field("i", "tax")}, {"scale": "19", "of": g.field("i", "net")}))
GROSS_ADDS_UP = the_invoice(g.cmp("eq", {"add": [g.field("i", "net"), g.field("i", "tax")]}, g.field("i", "gross")))


def contract(identity, requires):
    return g.contract(identity, {"invoice": g.text()}, INVOICE_KINDS, requires)


def gross_and_tax(condition=True):
    tax = {"id": "TAX_AT_19", "predicate": TAX_AT_19}
    if condition:
        tax["appliesWhen"] = NOT_REVERSE_CHARGE
    return contract("invoice-tax", [{"id": "GROSS_ADDS_UP", "predicate": GROSS_ADDS_UP}, tax])


def only_tax():
    return contract("invoice-tax-only", [{"appliesWhen": NOT_REVERSE_CHARGE, "id": "TAX_AT_19", "predicate": TAX_AT_19}])


def invoice(net, tax, gross, reverse_charge=None):
    fields = {"gross": str(gross), "id": "INV-1", "net": str(net), "tax": str(tax)}
    if reverse_charge is not None:
        fields["reverseCharge"] = reverse_charge
    return ("invoice", fields)


def env(*entries, closed=True):
    return g.environment({"invoice": "INV-1"}, g.facts(*entries), {"invoice"} if closed else set())


def case(name, description, c, e, values, decision):
    new_case(name, description, c, e, g.result(c, e, values, decision))


def build_cases():
    both, without, alone = gross_and_tax(), gross_and_tax(condition=False), only_tax()
    case("400-domestic", "A domestic invoice, 1000.00 + 190.00 = 1190.00: the tax check applies and holds.",
         both, env(invoice(100000, 19000, 119000, False)), ["TRUE", "TRUE"], "SUPPORTED")
    case("401-domestic-wrong-tax", "A domestic invoice taxed at 7 %: the tax check applies and fails.",
         both, env(invoice(100000, 7000, 107000, False)), ["TRUE", "FALSE"], "CONTRADICTED")
    case("402-reverse-charge", "Reverse charge, no tax shown: the tax check does not apply; the gross check holds.",
         both, env(invoice(100000, 0, 100000, True)), ["TRUE", "NOT_APPLICABLE"], "SUPPORTED")
    case("403-reverse-charge-without-condition", "The same invoice, the tax check without appliesWhen: CONTRADICTED, like a real failure.",
         without, env(invoice(100000, 0, 100000, True)), ["TRUE", "FALSE"], "CONTRADICTED")
    case("404-nothing-applies", "The contract's only requirement does not apply.",
         alone, env(invoice(100000, 0, 100000, True)), ["NOT_APPLICABLE"], "NOT_APPLICABLE")
    case("405-invoice-not-seen", "The invoice not yet seen, in a listing not declared complete: the check may yet apply.",
         alone, env(closed=False), ["UNKNOWN"], "UNDETERMINED")
    case("406-failure-where-it-does-not-apply", "Reverse charge with a tax of 10.00 shown: the tax check would fail, but does not apply.",
         both, env(invoice(100000, 1000, 101000, True)), ["TRUE", "NOT_APPLICABLE"], "SUPPORTED")
    case("407-condition-not-recorded", "reverseCharge not recorded: the condition is unknown, so the requirement is, though its predicate holds.",
         alone, env(invoice(100000, 19000, 119000)), ["UNKNOWN"], "UNDETERMINED")


def build_refusals():
    e = env(invoice(100000, 19000, 119000, False))
    refusal("420-applies-when-not-a-predicate", "appliesWhen is a term, not a predicate.",
            contract("refusals", [{"appliesWhen": g.field("i", "reverseCharge"), "id": "R", "predicate": TAX_AT_19}]),
            e, "CONTRACT_MALFORMED")
    refusal("421-applies-when-unbound-variable", "appliesWhen reads i, which it does not bind: it is evaluated with nothing bound.",
            contract("refusals", [{"appliesWhen": g.cmp("eq", g.field("i", "reverseCharge"), {"lit": False, "of": {"type": "bool"}}),
                                   "id": "R", "predicate": TAX_AT_19}]),
            e, "CONTRACT_ILL_FORMED")
    big = str(10**17)
    refusal("422-out-of-range-where-it-does-not-apply", "100 × tax = 10²⁰ is out of range; the requirement does not apply, but every term is evaluated.",
            only_tax(), env(invoice(big, big, str(2 * 10**17), True)), "ARITHMETIC_RANGE")


# --- Output ---------------------------------------------------------------------------------------


def lean_file():
    parts = [
        "import Applies.Theorems",
        "",
        "/-!",
        "Generated by `rfcs/0012/generate.py`; do not edit. For every proposed vector of RFC 0012 with a",
        "result, the model's value of each requirement and its decision, as the vector expects them.",
        "The environment is the vector's, settled by RFC 0008's generator; that step is tested against",
        "every published Language 1 case, not proved.",
        "-/",
        "",
        "namespace Applies.Vectors",
        "",
        "open Verified.Contract",
        "open Applies",
        "",
    ]
    for name, label, contract_value, e, expected in CHECKED:
        parts.append(f"/-- `{label}` -/")
        parts.append(lean_case(name, contract_value, e, expected))
        parts.append("")
    parts.append("end Applies.Vectors")
    return "\n".join(parts) + "\n"


def audit_file(current):
    block = [AUDIT_BEGIN] + [f"#print axioms Applies.Vectors.{name}" for name, *_ in CHECKED] + [AUDIT_END]
    if AUDIT_BEGIN in current:
        head = current[: current.index(AUDIT_BEGIN)]
        tail = current[current.index(AUDIT_END) + len(AUDIT_END) :]
        return head + "\n".join(block) + tail
    return current.rstrip("\n") + "\n\n" + "\n".join(block) + "\n"


def readme():
    lines = [
        "# Proposed vectors: when a requirement applies",
        "",
        "Generated by [`../../../generate.py`](../../../generate.py); do not edit. Proposed by",
        "[RFC 0012](../../../../0012-when-a-requirement-applies.md); not part of the conformance corpus. They add to",
        "RFC 0008's vectors, which this RFC leaves unchanged.",
        "",
        "- `cases/40x`: requirements with `appliesWhen`, and the decisions they give.",
        "- `cases/42x`: refusals.",
        "",
        f"**Checked against the model.** {len(CHECKED)} cases have a result. For each, `formal/Applies/Vectors.lean`",
        "states that the Lean model of RFC 0012 gives exactly its requirement values and decision, proved by",
        "`decide` and audited by `formal/check.sh`.",
        "",
        f"**Not checked against the model.** {len(NOT_CHECKED)} cases are refusals. The model has no static rules",
        "or arithmetic range, so these rest on the RFC's text:",
        "",
        "| Case | Refusal | Why |",
        "| --- | --- | --- |",
    ]
    for label, code, description in NOT_CHECKED:
        lines.append(f"| `{label}` | `{code}` | {description} |")
    return "\n".join(lines) + "\n"


def main():
    build_cases()
    build_refusals()
    outputs = [(OUT / path, json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n") for path, value in FILES]
    outputs.append((OUT / "README.md", readme()))
    outputs.append((LEAN, lean_file()))
    outputs.append((AUDIT, audit_file(AUDIT.read_text(encoding="utf-8"))))
    stale = []
    for file, text_value in outputs:
        if "--check" in sys.argv:
            if not file.is_file() or file.read_text(encoding="utf-8") != text_value:
                stale.append(str(file.relative_to(ROOT)))
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text_value, encoding="utf-8")
    if stale:
        sys.exit("not as generated: " + ", ".join(stale))
    verb = "are as generated" if "--check" in sys.argv else "written"
    print(f"{len(FILES)} vector files ({len(CHECKED)} cases checked by the model, {len(NOT_CHECKED)} refusals) {verb}.")


if __name__ == "__main__":
    main()
