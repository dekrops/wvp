#!/usr/bin/env python3
"""Writes the vectors proposed by RFC 0011 (aggregates as terms, products of terms), and their Lean checks.

    python3 rfcs/0011/generate.py [--check]

Built on RFC 0008's generator (`rfcs/0008/generate.py`), which it imports for settling an
environment and for the shape of a case. Two outputs:

* `rfcs/0011/vectors/work-contract/v2/`:
  * `cases/3*`: new. The three controls RFC 0011's Motivation names (the amounts add up, the tax at
    the group's own rate, the cumulative three-way match), and the refusals it lists.
  * `term-form/`: every RFC 0008 aggregate vector with a result, its aggregate predicates rewritten
    as a comparison with an aggregate term, with RFC 0008's expectation unchanged.
* `rfcs/0011/formal/WCL2T/Vectors.lean`: for every case with a result, a theorem that the Lean model
  of RFC 0011 (`WCL2T.Pred.eval`, `WCL2T.evaluate`) gives exactly its expected requirement values and
  decision, proved by `decide`. `check.sh` builds and audits them.

Refusals (static rules, the arithmetic range) are not in the model; they rest on the RFC's text, and
`vectors/README.md` lists them. Standard library only, deterministic; --check fails if any output
differs from what would be written. These are proposals, not part of the conformance corpus.
"""

import importlib.util
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
RFC0008 = HERE.parent / "0008"
_spec = importlib.util.spec_from_file_location("rfc0008_generate", RFC0008 / "generate.py")
g = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(g)

OUT = HERE / "vectors" / "work-contract" / "v2"
LEAN = HERE / "formal" / "WCL2T" / "Vectors.lean"
AUDIT = HERE / "formal" / "Audit.lean"
AUDIT_BEGIN = "-- Generated by rfcs/0011/generate.py: one theorem per proposed vector with a result."
AUDIT_END = "-- End of generated vector theorems."

FILES = []  # (path relative to OUT, value)
CHECKED = []  # (theorem name, file label, contract, environment, expected)
NOT_CHECKED = []  # (file label, refusal code, description)


# --- Translation into the Lean model of RFC 0011 ---------------------------------------------------


def lean_fn(agg):
    if agg["aggregate"] == "sum":
        return f"(.sum {g.lean_string(agg['field'])})"
    if "distinct" in agg:
        return f"(.countDistinct {g.lean_string(agg['distinct'])})"
    return ".count"


def lean_term(term):
    if "aggregate" in term:
        if "cmp" in term or "than" in term:
            raise ValueError(f"an aggregate term has no cmp or than: {term}")
        body = lean_pred(term["where"])
        return f"(.agg {lean_fn(term)} {g.lean_string(term['of'])} {g.lean_string(term['in'])} {body})"
    if "mul" in term:
        left, right = (lean_term(t) for t in term["mul"])
        return f"(.mul {left} {right})"
    if "add" in term or "sub" in term:
        op = "add" if "add" in term else "sub"
        left, right = (lean_term(t) for t in term[op])
        return f"(.{op} {left} {right})"
    if "scale" in term:
        return f"(.scale ({int(term['scale'])}) {lean_term(term['of'])})"
    if "abs" in term:
        return f"(.abs {lean_term(term['abs'])})"
    if "lit" in term:
        return f"(.lit {g.lean_ty(term['of'])} {g.lean_value(term['of'], term['lit'])})"
    if "input" in term:
        return f"(.input {g.lean_string(term['input'])})"
    if "param" in term:
        return f"(.param {g.lean_string(term['param'])})"
    if "var" in term:
        return f"(.field {g.lean_string(term['var'])} {g.lean_string(term['field'])})"
    raise ValueError(f"not a term: {term}")


def lean_pred(pred):
    if "aggregate" in pred:
        body = lean_pred(pred["where"])
        bound = lean_term(pred["than"])
        return f"(.agg {lean_fn(pred)} {g.lean_string(pred['of'])} {g.lean_string(pred['in'])} {body} .{pred['cmp']} {bound})"
    if "cmp" in pred:
        return f"(.cmp .{pred['cmp']} {lean_term(pred['left'])} {lean_term(pred['right'])})"
    for op in ("and", "or"):
        if op in pred:
            parts = [lean_pred(p) for p in pred[op]]
            lowered = parts[-1]
            for part in reversed(parts[:-1]):
                lowered = f"(.{op} {part} {lowered})"
            return lowered
    if "not" in pred:
        return f"(.not {lean_pred(pred['not'])})"
    if "exists" in pred:
        return f"(.ex {g.lean_string(pred['exists'])} {g.lean_string(pred['in'])} {lean_pred(pred['where'])})"
    if "forall" in pred:
        return f"(.all {g.lean_string(pred['forall'])} {g.lean_string(pred['in'])} {lean_pred(pred['holds'])})"
    raise ValueError(f"not a predicate: {pred}")


def lean_case(name, contract, environment, expected):
    records, closed, _, _ = g.settle(contract, environment)
    kinds = contract["kinds"]
    inputs = [(k, f"some {g.lean_value(contract['inputs'][k], v)}") for k, v in sorted(environment["inputs"].items())]
    params = [(k, f"some {g.lean_value(p['type'], p['value'])}") for k, p in sorted(contract["policy"].items())]

    def record(kind, fields):
        pairs = ", ".join(
            f"({g.lean_string(f)}, {g.lean_value(kinds[kind]['fields'][f], v)})" for f, v in sorted(fields.items())
        )
        return f"⟨[{pairs}]⟩"

    record_lists = [(k, "[" + ", ".join(record(k, f) for f in rs) + "]") for k, rs in sorted(records.items()) if rs]
    closed_kinds = [(k, "true") for k in sorted(closed)]
    preds = [lean_pred(r["predicate"]) for r in contract["requires"]]
    values = ", ".join("." + r["value"].lower() for r in expected["requirements"])
    decision = "." + expected["decision"].lower()
    return "\n".join(
        [
            f"def {name}.env : Env where",
            f"  inputs := {g.lean_lookup('n', inputs, 'none')}",
            f"  params := {g.lean_lookup('n', params, 'none')}",
            f"  records := {g.lean_lookup('k', record_lists, '[]')}",
            f"  closed := {g.lean_lookup('k', closed_kinds, 'false')}",
            "",
            f"def {name}.requirements : List WCL2T.Pred := [",
            ",\n".join("  " + p for p in preds),
            "]",
            "",
            f"theorem {name} :",
            f"    {name}.requirements.map (fun r => r.eval {name}.env []) = [{values}] ∧",
            f"      WCL2T.evaluate {name}.env {name}.requirements = {decision} := by",
            "  decide",
        ]
    )


# --- Cases -----------------------------------------------------------------------------------------


def add_case(label, case, contract, description):
    expected = case["expected"]
    if "refused" in expected:
        NOT_CHECKED.append((label, expected["refused"], description))
        return
    _, _, ignored, conflicts = g.settle(contract, case["environment"])
    if expected["ignored"] != ignored or expected["conflicts"] != conflicts:
        sys.exit(f"{label}: settling the environment does not reproduce the expected ignored and conflicts")
    if [r["id"] for r in expected["requirements"]] != [r["id"] for r in contract["requires"]]:
        sys.exit(f"{label}: the expected requirements are not the contract's, in order")
    CHECKED.append((g.lean_name(label), label, contract, case["environment"], expected))


def new_case(name, description, contract_value, env, expected):
    label = f"cases/{name}.json"
    value = {"contract": contract_value, "description": description, "environment": env, "expected": expected}
    add_case(label, value, contract_value, description)
    FILES.append((label, value))


def refusal(name, description, contract_value, env, code):
    new_case(name, description, contract_value, env, {"refused": code})


def int_ty():
    return {"type": "int"}


def money(n):
    return {"lit": str(n), "of": g.eur()}


def agg_term(fn, var, kind, where, field=None):
    term = {"aggregate": fn, "in": kind, "of": var, "where": where}
    if field is not None:
        term["field"] = field
    return term


# The amounts add up, and the tax at each group's own rate.
RATE_KINDS = {
    "invoice": {"fields": {"gross": g.eur(), "id": g.text()}, "key": ["id"]},
    "rateGroup": {
        "fields": {"id": g.text(), "invoice": g.text(), "net": g.eur(), "rateBps": int_ty(), "tax": g.eur()},
        "key": ["id"],
    },
}


def groups_of(field_name):
    return agg_term("sum", "g", "rateGroup", g.cmp("eq", g.field("g", "invoice"), g.field("i", "id")), field_name)


AMOUNTS_ADD_UP = {
    "exists": "i",
    "in": "invoice",
    "where": {
        "and": [
            g.cmp("eq", g.field("i", "id"), {"input": "invoice"}),
            g.cmp("eq", {"add": [groups_of("net"), groups_of("tax")]}, g.field("i", "gross")),
        ]
    },
}

# 10000·(tax − 1) ≤ rateBps·net + 5000 < 10000·(tax + 2): the tax is net × rate, rounded half up,
# within a cent. rateBps·net is money in 1/10,000ths of a cent.
ROUNDED = {"add": [{"mul": [g.field("g", "rateBps"), g.field("g", "net")]}, money(5000)]}
TAX_AT_GROUP_RATE = {
    "forall": "g",
    "in": "rateGroup",
    "holds": {
        "or": [
            {"not": g.cmp("eq", g.field("g", "invoice"), {"input": "invoice"})},
            {
                "and": [
                    g.cmp("le", {"scale": "10000", "of": {"sub": [g.field("g", "tax"), money(1)]}}, ROUNDED),
                    g.cmp("lt", ROUNDED, {"scale": "10000", "of": {"add": [g.field("g", "tax"), money(2)]}}),
                ]
            },
        ]
    },
}


def rate_contract():
    return g.contract(
        "invoice-rate-groups",
        {"invoice": g.text()},
        RATE_KINDS,
        [
            {"id": "AMOUNTS_ADD_UP", "predicate": AMOUNTS_ADD_UP},
            {"id": "TAX_AT_GROUP_RATE", "predicate": TAX_AT_GROUP_RATE},
        ],
    )


def gross(amount, invoice_id="INV-1"):
    return ("invoice", {"gross": str(amount), "id": invoice_id})


def group(id_, rate_bps, net, tax, invoice_id="INV-1"):
    return ("rateGroup", {"id": id_, "invoice": invoice_id, "net": str(net), "rateBps": str(rate_bps), "tax": str(tax)})


def build_rate_groups():
    c = rate_contract()
    both = {"invoice", "rateGroup"}

    def env(entries, complete=both):
        return g.environment({"invoice": "INV-1"}, g.facts(*entries), complete)

    def case(name, description, entries, values, decision, complete=both):
        e = env(entries, complete)
        new_case(name, description, c, e, g.result(c, e, values, decision))

    # 168.03 at 19 % is 31.9257, rounded 31.93; 100.00 at 7 % is 7.00. Gross 168.03 + 31.93 + 100.00 + 7.00.
    case("300-amounts-add-up", "Two rate groups, 19 % and 7 %: Σ net + Σ tax = gross, and each tax is its net at its rate.",
         [gross(30696), group("G-1", 1900, 16803, 3193), group("G-2", 700, 10000, 700)], ["TRUE", "TRUE"], "SUPPORTED")
    case("301-gross-a-cent-off", "The gross is one cent more than Σ net + Σ tax.",
         [gross(30697), group("G-1", 1900, 16803, 3193), group("G-2", 700, 10000, 700)], ["FALSE", "TRUE"], "CONTRADICTED")
    case("302-rate-groups-open", "No source declared the rate groups complete: neither sum has a value.",
         [gross(30696), group("G-1", 1900, 16803, 3193), group("G-2", 700, 10000, 700)], ["UNKNOWN", "UNKNOWN"], "UNDETERMINED",
         complete={"invoice"})
    case("303-other-invoice-not-counted", "A rate group of another invoice is in neither sum, and its tax is not checked.",
         [gross(30696), group("G-1", 1900, 16803, 3193), group("G-2", 700, 10000, 700), group("G-3", 1900, 99999, 1, "INV-2")],
         ["TRUE", "TRUE"], "SUPPORTED")
    case("304-rate-read-not-listed", "10 %, a rate the contract does not list: read from the group.",
         [gross(11000), group("G-1", 1000, 10000, 1000)], ["TRUE", "TRUE"], "SUPPORTED")
    case("305-tax-two-cents-high", "Tax 31.95 on 168.03 at 19 % (31.9257): two cents high.",
         [gross(19998), group("G-1", 1900, 16803, 3195)], ["TRUE", "FALSE"], "CONTRADICTED")
    case("306-tax-a-cent-low", "Tax 31.92 on 168.03 at 19 % (31.9257, rounded 31.93): within a cent.",
         [gross(19995), group("G-1", 1900, 16803, 3192)], ["TRUE", "TRUE"], "SUPPORTED")
    case("307-tax-two-cents-low", "Tax 31.91 on 168.03 at 19 % (31.9257, rounded 31.93): two cents low.",
         [gross(19994), group("G-1", 1900, 16803, 3191)], ["TRUE", "FALSE"], "CONTRADICTED")
    case("308-no-rate-groups", "No rate groups, in a complete listing: both sums are 0, so the gross must be 0.",
         [gross(100)], ["FALSE", "TRUE"], "CONTRADICTED")


# The cumulative three-way match.
MATCH_KINDS = {
    "invoiceLine": {"fields": {"id": g.text(), "order": g.text(), "qty": int_ty()}, "key": ["id"]},
    "receipt": {"fields": {"id": g.text(), "order": g.text(), "qty": int_ty()}, "key": ["id"]},
}


def of_order(var):
    return g.cmp("eq", g.field(var, "order"), {"input": "order"})


INVOICED_WITHIN_RECEIVED = g.cmp(
    "le",
    agg_term("sum", "l", "invoiceLine", of_order("l"), "qty"),
    agg_term("sum", "r", "receipt", of_order("r"), "qty"),
)


def build_three_way():
    c = g.contract(
        "cumulative-three-way-match",
        {"order": g.text()},
        MATCH_KINDS,
        [{"id": "INVOICED_WITHIN_RECEIVED", "predicate": INVOICED_WITHIN_RECEIVED}],
    )
    both = {"invoiceLine", "receipt"}

    def line(id_, qty, order_id="PO-7"):
        return ("invoiceLine", {"id": id_, "order": order_id, "qty": str(qty)})

    def receipt(id_, qty, order_id="PO-7"):
        return ("receipt", {"id": id_, "order": order_id, "qty": str(qty)})

    def case(name, description, entries, value, decision, complete=both):
        e = g.environment({"order": "PO-7"}, g.facts(*entries), complete)
        new_case(name, description, c, e, g.result(c, e, [value], decision))

    case("310-invoiced-within-received", "Invoiced 5 + 3 against received 6 + 4.",
         [line("L-1", 5), line("L-2", 3), receipt("R-1", 6), receipt("R-2", 4)], "TRUE", "SUPPORTED")
    case("311-invoiced-one-beyond", "Invoiced 5 + 6 against received 6 + 4: one unit beyond.",
         [line("L-1", 5), line("L-2", 6), receipt("R-1", 6), receipt("R-2", 4)], "FALSE", "CONTRADICTED")
    case("312-receipts-open", "No source declared the receipts complete: received has no value.",
         [line("L-1", 5), receipt("R-1", 6)], "UNKNOWN", "UNDETERMINED", complete={"invoiceLine"})
    case("313-invoiced-equals-received", "Invoiced 10 against received 10: at the bound.",
         [line("L-1", 10), receipt("R-1", 10)], "TRUE", "SUPPORTED")
    case("314-other-order-not-counted", "A receipt of another order does not cover this order's invoices.",
         [line("L-1", 5), receipt("R-1", 4), receipt("R-2", 99, "PO-8")], "FALSE", "CONTRADICTED")


def build_refusals():
    c = rate_contract()
    env = g.environment({"invoice": "INV-1"}, g.facts(gross(30696), group("G-1", 1900, 16803, 3193)), {"invoice", "rateGroup"})

    def with_requirement(pred):
        return g.contract("refusals", {"invoice": g.text()}, RATE_KINDS, [{"id": "R", "predicate": pred}])

    refusal("320-mul-of-two-money", "mul of two money operands: the product has no unit the language has.",
            with_requirement({"forall": "g", "in": "rateGroup",
                              "holds": g.cmp("le", {"mul": [g.field("g", "net"), g.field("g", "tax")]}, g.field("g", "net"))}),
            env, "CONTRACT_ILL_FORMED")
    big = str(10**10)
    refusal("321-product-out-of-range", "rateBps × net = 10¹⁰ × 10¹⁰ = 10²⁰, beyond 2⁶³.", c,
            g.environment({"invoice": "INV-1"}, g.facts(gross(30696), group("G-1", big, big, 3193)), {"invoice", "rateGroup"}),
            "ARITHMETIC_RANGE")
    half = str(2**62)
    refusal("322-aggregate-term-out-of-range", "Σ net over two groups of 2⁶² each is 2⁶³: the aggregate term is out of range.", c,
            g.environment({"invoice": "INV-1"},
                          g.facts(gross(30696), group("G-1", 0, half, 0), group("G-2", 0, half, 0)), {"invoice", "rateGroup"}),
            "ARITHMETIC_RANGE")
    deep = {"forall": "a", "in": "rateGroup", "holds": {"forall": "b", "in": "rateGroup", "holds": {"forall": "c", "in": "rateGroup",
            "holds": g.cmp("le", agg_term("count", "d", "rateGroup", g.cmp("eq", g.field("d", "id"), g.field("c", "id"))), g.lit_int(1))}}}
    refusal("323-aggregate-term-too-deep", "An aggregate term inside three quantifiers: depth 4, over the limit of 3.",
            with_requirement(deep), env, "CONTRACT_ILL_FORMED")
    refusal("324-aggregate-term-with-cmp", "An aggregate with cmp and than is a predicate, not a term: it cannot be added.",
            with_requirement({"exists": "i", "in": "invoice", "where": g.cmp("eq",
                {"add": [dict(groups_of("net"), cmp="le", than=money(0)), groups_of("tax")]}, g.field("i", "gross"))}),
            env, "CONTRACT_MALFORMED")


def as_terms(pred):
    """RFC 0008's aggregate predicates, rewritten as a comparison with the aggregate term."""
    if isinstance(pred, dict):
        if "aggregate" in pred and "cmp" in pred:
            term = {k: as_terms(v) for k, v in pred.items() if k not in ("cmp", "than")}
            return {"cmp": pred["cmp"], "left": term, "right": as_terms(pred["than"])}
        return {k: as_terms(v) for k, v in pred.items()}
    if isinstance(pred, list):
        return [as_terms(p) for p in pred]
    return pred


def build_term_form():
    for source in sorted((RFC0008 / "vectors" / "work-contract" / "v2" / "cases").glob("2*.json")):
        value = json.loads(source.read_text(encoding="utf-8"))
        if "refused" in value["expected"]:
            continue
        rewritten = as_terms(value["contract"])
        if rewritten == value["contract"]:
            continue
        value["contract"] = rewritten
        value["description"] = f"RFC 0008's `{source.name}`, its aggregates as terms. " + value.get("description", "")
        label = f"term-form/{source.name}"
        add_case(label, value, rewritten, value["description"])
        FILES.append((label, value))


# --- Output ---------------------------------------------------------------------------------------


def lean_file():
    parts = [
        "import WCL2T.Semantics",
        "",
        "/-!",
        "Generated by `rfcs/0011/generate.py`; do not edit. For every proposed vector of RFC 0011 with a",
        "result, the model's value of each requirement and its decision, as the vector expects them.",
        "The environment is the vector's, settled by RFC 0008's generator; that step is tested against",
        "every published Language 1 case, not proved.",
        "-/",
        "",
        "namespace WCL2T.Vectors",
        "",
        "open Verified.Contract",
        "open WCL2T",
        "",
    ]
    for name, label, contract_value, env, expected in CHECKED:
        parts.append(f"/-- `{label}` -/")
        parts.append(lean_case(name, contract_value, env, expected))
        parts.append("")
    parts.append("end WCL2T.Vectors")
    return "\n".join(parts) + "\n"


def audit_file(current):
    block = [AUDIT_BEGIN] + [f"#print axioms WCL2T.Vectors.{name}" for name, *_ in CHECKED] + [AUDIT_END]
    if AUDIT_BEGIN in current:
        head = current[: current.index(AUDIT_BEGIN)]
        tail = current[current.index(AUDIT_END) + len(AUDIT_END) :]
        return head + "\n".join(block) + tail
    return current.rstrip("\n") + "\n\n" + "\n".join(block) + "\n"


def readme():
    term_form = sum(1 for label, *_ in FILES if label.startswith("term-form/"))
    lines = [
        "# Proposed vectors: aggregates as terms",
        "",
        "Generated by [`../../../generate.py`](../../../generate.py); do not edit. Proposed by",
        "[RFC 0011](../../../../0011-aggregate-terms.md); not part of the conformance corpus. They add to",
        "RFC 0008's vectors, which this RFC leaves unchanged.",
        "",
        "- `cases/30x`: the amounts add up, and the tax at each rate group's own rate (`mul`).",
        "- `cases/31x`: the cumulative three-way match, a sum compared with a sum.",
        "- `cases/32x`: refusals.",
        f"- `term-form/`: {term_form} of RFC 0008's aggregate vectors, each aggregate predicate written as a",
        "  comparison with an aggregate term, with RFC 0008's expectation unchanged.",
        "",
        f"**Checked against the model.** {len(CHECKED)} cases have a result. For each, `formal/WCL2T/Vectors.lean`",
        "states that the Lean model of RFC 0011 gives exactly its requirement values and decision, proved by",
        "`decide` and audited by `formal/check.sh`.",
        "",
        f"**Not checked against the model.** {len(NOT_CHECKED)} cases are refusals. The model has no static rules",
        "or arithmetic range, so these rest on the RFC's text:",
        "",
        "| Case | Refusal | Why |",
        "| --- | --- | --- |",
    ]
    for label, code, description in NOT_CHECKED:
        lines.append(f"| `{label}` | `{code}` | {description.replace('|', chr(92) + '|')} |")
    return "\n".join(lines) + "\n"


def main():
    build_rate_groups()
    build_three_way()
    build_refusals()
    build_term_form()
    outputs = [(OUT / path, json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n") for path, value in FILES]
    outputs.append((OUT / "README.md", readme()))
    outputs.append((LEAN, lean_file()))
    outputs.append((AUDIT, audit_file(AUDIT.read_text(encoding="utf-8"))))
    stale = []
    for file, text_value in outputs:
        if "--check" in sys.argv:
            if not file.is_file() or file.read_text(encoding="utf-8") != text_value:
                stale.append(str(file.relative_to(ROOT)))
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text_value, encoding="utf-8")
    if stale:
        sys.exit("not as generated: " + ", ".join(stale))
    verb = "are as generated" if "--check" in sys.argv else "written"
    print(f"{len(FILES)} vector files ({len(CHECKED)} cases checked by the model, {len(NOT_CHECKED)} refusals) {verb}.")


if __name__ == "__main__":
    main()
